#!/usr/bin/env python3
"""I/O test design for the pin plan: every core-side port of the Interface Designer project gets a flop, then the
whole project goes through Efinity synthesis, place and route and bitstream generation (user, 2026-11-19).

    source ~/efinity/2026.1/bin/setup.sh
    python3 efinity/pinplan/pinplan.py              # efinity/pinplan/build/ti135_pinplan.peri.xml + outflow/
    python3 efinity/io_test/make_io_test.py         # top level, constraints and project file into the same build/
    cd efinity/pinplan/build && efx_run.py ti135_pinplan.xml --flow compile

It proves that Efinity accepts the pin plan as a buildable design (GPIO placement, bank standards, PLL references,
the DDR block with its pin swizzle, the hard SoC and JTAG), not that any interface works: the logic is one shift
register per clock domain, fed by the XOR of that domain's registered inputs and driving its outputs, so no port
is optimised away. Everything is generated into efinity/pinplan/build/ (git-ignored).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(HERE, "..", "pinplan", "build")
NAME = "ti135_pinplan"
TIMING_MODEL = os.environ.get("IO_TEST_TIMING_MODEL", "I3")
DEVICE = os.environ.get("IO_TEST_DEVICE", "Ti135N484")
FAMILY = "Topaz" if DEVICE.startswith("Tz") else "Titanium"

tmpl = open(os.path.join(BUILD, "outflow", NAME + "_template.v")).read()
ports = [(d, int(w) + 1 if w else 1, n) for d, w, n in
         re.findall(r"\(\* syn_peri_port = 0 \*\) (input|output) (?:\[(\d+):0\] )?(\w+)", tmpl)]
CLOCKS = [n for d, w, n in ports if d == "input" and
          (re.fullmatch(r"pll_\w+_CLKOUT\d", n) or n in ("rgmii_rxc", "emmc_ds", "soc_jtag_TCK", "soc_jtag_DRCK"))]
SKIP = {"refclk_bl0", "refclk_bl1", "refclk_bl2"}          # PLL reference pins: the PLLs use them, the core does not
# one free-running toggle per clock that has no bus of its own, so every PLL output is used
TOGGLE = {"rgmii_txc": "pll_bl0_CLKOUT2", "led0_n": "pll_bl1_CLKOUT0", "led1_n": "pll_bl1_CLKOUT1",
          "lcd_led": "pll_bl2_CLKOUT4", "soc_AXIAINTERRUPT": "soc_jtag_DRCK"}


def domain(n):
    if n.startswith("ddr_"):
        return "pll_bl2_CLKOUT0"                      # AXI0_CLK_INPUT_PIN / CTRL_CLK_PIN in pinplan.py
    if n.startswith("soc_jtag_"):
        return "soc_jtag_TCK"
    if n.startswith("rgmii_rx"):
        return "rgmii_rxc"
    if n.startswith("rgmii_tx"):
        return "pll_bl0_CLKOUT1"
    if n.startswith("emmc_dat") and n.endswith("_IN"):
        return "emmc_ds"
    return "pll_bl0_CLKOUT0"


v = [f"// generated by efinity/io_test/make_io_test.py: do not edit\nmodule {NAME} ("]
v += [f"    {d} {'[%d:0] ' % (w - 1) if w > 1 else ''}{n}," for d, w, n in ports]
v[-1] = v[-1].rstrip(",")
v.append(");")
MAIN = "pll_bl0_CLKOUT0"
orphans = []                 # result bits of domains that have inputs but no output: they join the main domain's inputs
for ck in sorted(CLOCKS, key=lambda c: c == MAIN):
    ins = [(w, n) for d, w, n in ports if d == "input" and n not in CLOCKS and n not in SKIP and domain(n) == ck]
    outs = [(w, n) for d, w, n in ports if d == "output" and n not in TOGGLE and domain(n) == ck]
    k = re.sub(r"\W", "_", ck)
    if ck == MAIN:
        ins += [(1, o) for o in orphans]
    elif ins and not outs and ck not in TOGGLE.values():
        orphans.append(f"x2_{k}")
    if ins:
        nin = sum(w for w, _ in ins)
        v.append(f"    reg [{nin - 1}:0] in_{k};\n    always @(posedge {ck}) in_{k} <= {{{', '.join(n for _, n in ins)}}};")
        groups = (nin + 31) // 32
        v.append(f"    reg [{groups - 1}:0] x1_{k};\n    reg x2_{k};\n    always @(posedge {ck}) begin")
        for g in range(groups):
            hi = min(nin, 32 * g + 32) - 1
            v.append(f"        x1_{k}[{g}] <= ^in_{k}[{hi}:{32 * g}];")
        v.append(f"        x2_{k} <= ^x1_{k};\n    end")
    else:
        v.append(f"    reg x2_{k} = 1'b0;\n    always @(posedge {ck}) x2_{k} <= ~x2_{k};")
    if outs:
        nout = sum(w for w, _ in outs)
        v.append(f"    reg [{nout - 1}:0] sr_{k};\n    always @(posedge {ck}) sr_{k} <= {{sr_{k}[{nout - 2}:0], x2_{k}}};" if nout > 1 else
                 f"    reg [0:0] sr_{k};\n    always @(posedge {ck}) sr_{k} <= x2_{k};")
        v.append(f"    assign {{{', '.join(n for _, n in outs)}}} = sr_{k};")
    for o, c in TOGGLE.items():
        if c == ck:
            v.append(f"    assign {o} = x2_{k};")
v.append("endmodule\n")
open(os.path.join(BUILD, "io_test_top.v"), "w").write("\n".join(v))

sdc = open(os.path.join(BUILD, "outflow", NAME + ".pt.sdc")).read()
sdc = sdc.replace("create_clock -period <USER_PERIOD> -name emmc_ds", "create_clock -period 5.000 -name emmc_ds")
sdc = sdc.replace("create_clock -period <USER_PERIOD> -name rgmii_rxc", "create_clock -period 8.000 -name rgmii_rxc")
sdc = re.sub(r"# (create_clock -period )<USER_PERIOD>( -name soc_jtag_(?:TCK|DRCK))", r"\g<1>100.000\2", sdc)
assert "<USER_PERIOD>" not in "\n".join(l for l in sdc.split("\n") if not l.startswith("#")), "unset clock period"
sdc += ("\n# io_test: the domains are independent shift registers\nset_clock_groups -asynchronous " +
        " ".join("-group {%s}" % c for c in CLOCKS) + "\n")
open(os.path.join(BUILD, "io_test.sdc"), "w").write(sdc)

xml = f"""<?xml version="1.0" encoding="UTF-8"?>
<efx:project name="{NAME}" description="pin plan I/O test" sw_version="2026.1.132" xmlns:efx="http://www.efinixinc.com/enf_proj" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://www.efinixinc.com/enf_proj enf_proj.xsd">
    <efx:device_info>
        <efx:family name="{FAMILY}"/>
        <efx:device name="{DEVICE}"/>
        <efx:timing_model name="{TIMING_MODEL}"/>
    </efx:device_info>
    <efx:design_info def_veri_version="verilog_2k" def_vhdl_version="vhdl_2008">
        <efx:top_module name="{NAME}"/>
        <efx:design_file name="io_test_top.v" version="default" library="default"/>
        <efx:top_vhdl_arch name=""/>
    </efx:design_info>
    <efx:constraint_info>
        <efx:sdc_file name="io_test.sdc"/>
        <efx:inter_file name=""/>
    </efx:constraint_info>
    <efx:sim_info/>
    <efx:misc_info/>
    <efx:ip_info/>
    <efx:synthesis tool_name="efx_map">
        <efx:param name="work_dir" value="work_syn" value_type="e_string"/>
        <efx:param name="write_efx_verilog" value="on" value_type="e_bool"/>
    </efx:synthesis>
    <efx:place_and_route tool_name="efx_pnr">
        <efx:param name="work_dir" value="work_pnr" value_type="e_string"/>
        <efx:param name="verbose" value="off" value_type="e_bool"/>
        <efx:param name="seed" value="1" value_type="e_integer"/>
    </efx:place_and_route>
    <efx:bitstream_generation tool_name="efx_pgm">
        <efx:param name="mode" value="active" value_type="e_option"/>
        <efx:param name="width" value="4" value_type="e_option"/>
        <efx:param name="enable_roms" value="smart" value_type="e_option"/>
        <efx:param name="spi_low_power_mode" value="on" value_type="e_bool"/>
        <efx:param name="io_weak_pullup" value="on" value_type="e_bool"/>
        <efx:param name="oscillator_clock_divider" value="DIV8" value_type="e_option"/>
        <efx:param name="bitstream_compression" value="on" value_type="e_bool"/>
    </efx:bitstream_generation>
    <efx:debugger>
        <efx:param name="work_dir" value="work_dbg" value_type="e_string"/>
        <efx:param name="auto_instantiation" value="off" value_type="e_bool"/>
        <efx:param name="profile" value="NONE" value_type="e_string"/>
    </efx:debugger>
</efx:project>
"""
open(os.path.join(BUILD, NAME + ".xml"), "w").write(xml)
print(f"{len(ports)} ports ({sum(w for _, w, _ in ports)} bits), clocks: {', '.join(CLOCKS)}")
print("wrote io_test_top.v, io_test.sdc and", NAME + ".xml", "in", os.path.normpath(BUILD))
