"""results/results.csv (+ results_xtalk.csv, zsolve.csv) -> results/results.md.   python3 report.py

Every figure is the worst case over the receivers of the case (both U801 channels for CA/CK), the receiver ball and
die, and the corners asked for. Margins are against the Rx mask (run_si.masks): v_margin = eye opening inside the mask
window minus the mask height, t_margin = eye width at the mask height minus the mask width.
"""
import csv, os, collections

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')


def load(name):
    p = os.path.join(RES, name)
    if not os.path.exists(p): return []
    rows = list(csv.DictReader(open(p)))
    for r in rows:
        for k, v in r.items():
            try: r[k] = float(v)
            except (TypeError, ValueError): pass
    return rows


import sys
R = load(sys.argv[1] if len(sys.argv) > 1 else 'results.csv')
# reads are judged at the FPGA die: TI's read mask is defined at the SoC die pad, and with the package drawn as a line
# (--pkg netlen) the FPGA ball is a mid-point of the package with the standing wave of its own reflection on it
R = [r for r in R if not (r['kind'] in ('dq_read', 'dqs_read') and r['where'] == 'ball')]
X = load('results_xtalk.csv')
Z = load('zsolve.csv')
# baseline-setting cases (gen_sch.py BASE): DQ/DM per net, DQS, CK, CA/CS/CKE with CA ODT 40
GROUPS = [('dq_write', 'DQ/DM write (FPGA 40 Ω → DRAM ODT 60)', lambda c: c.startswith('w_d') and '_d' not in c[3:] and 'dqs' not in c),
          ('dq_read', 'DQ/DM read (DRAM PDDS 40 → FPGA ODT 60)', lambda c: c.startswith('r_d') and '_p' not in c[3:] and 'dqs' not in c),
          ('dqs_write', 'DQS write (pair)', lambda c: c.startswith('w_dqs')),
          ('dqs_read', 'DQS read (pair)', lambda c: c.startswith('r_dqs')),
          ('ck', 'CK (pair, T, CK ODT 40)', lambda c: c == 'ck_40'),
          ('ca', 'CA (T, CA ODT 40)', lambda c: c.startswith('ca') and c.endswith('_40')),
          ('ca', 'CS (point to point, ODT 40)', lambda c: c.startswith('cs') and c.endswith('_40')),
          ('ca', 'CKE (T, no ODT)', lambda c: c.startswith('cke'))]


def worst(rows):
    return dict(eh=min(r['eh_mV'] for r in rows), ew=min(r['ew0_ps'] for r in rows),
                vm=min(r['v_margin_mV'] for r in rows),
                tm=min((r['t_margin_ps'] if r['t_margin_ps'] == r['t_margin_ps'] else -999.0) for r in rows),  # nan: no opening at the mask height
                vmax=max(r['vmax_mV'] for r in rows), vmin=min(r['vmin_mV'] for r in rows),
                osa=max(r['os_area_Vns'] for r in rows), ok=all(r['limits_ok'] in (True, 'True') for r in rows),
                n=len(rows))


def sel(rows, **kw):
    return [r for r in rows if all((r[k] == v) if not callable(v) else v(r[k]) for k, v in kw.items())]


def fmt(w, ref=None):
    d = '' if ref is None or ref['tm'] == 0 else f" ({(w['tm'] - ref['tm']) / abs(ref['tm']) * 100:+.0f} %)"
    return (f"{w['eh']:.0f} | {w['ew']:.0f} | {w['vm']:+.0f} | {w['tm']:+.0f}{d} | {w['vmax']:.0f} / {w['vmin']:.0f} | "
            f"{'ok' if w['ok'] else '**over**'}")


HDR = '| eye height (mV) | eye width (ps) | margin V (mV) | margin t (ps) (vs today) | Vmax / Vmin (mV) | ±0.3 V |'
out = ['# LPDDR4 IBIS results (generated by report.py)', '',
       'Worst case over nets, receivers, and ball/die (DRAM side; the FPGA side is judged at the die). DRAM = Winbond W66CL2NQUAFJ **stand-in**. FPGA package: Efinix '
       'net-length delay as a 50.6 Ω line unless marked *pkg file*.', '']
if R:
    widths = sorted({(r['w_in'], r['w_out']) for r in R if r['pkg'] == 'netlen' and r['diff_in'] == '0.14/0.15'
                     and r['diff_out'] == '0.20/0.20'}, key=lambda x: (-x[0] - x[1]))
    KEY = [(0.18, 0.25), (0.12, 0.15), (0.10, 0.10), (0.09, 0.09)]
    SE_GROUPS = [g for g in GROUPS if g[0] not in ('dqs_write', 'dqs_read', 'ck')]   # pairs: own table below
    for rate in sorted({r['rate'] for r in R}):
        for corners, cname, wl in ((('typ',), 'typ, every width', widths),
                                   (('typ', 'min', 'max'), 'worst of typ / min / max, key widths', KEY)):
            out += [f'## {rate:g} MT/s, single-ended width sweep, {cname}', '']
            for kind, title, f in SE_GROUPS:
                out += [f'### {title}', '', '| inner / outer (mm) ' + HDR, '|---|---|---|---|---|---|---|']
                ref = None
                for wi, wo in wl:
                    rs = sel(R, rate=rate, w_in=wi, w_out=wo, pkg='netlen', diff_in='0.14/0.15', diff_out='0.20/0.20',
                             corner=lambda c: c in corners, case=f)
                    if not rs or {r['corner'] for r in rs} != set(corners): continue
                    w = worst(rs); ref = ref or w
                    out.append(f'| {wi:.2f} / {wo:.2f} | ' + fmt(w, ref) + ' |')
                out.append('')
    # settings
    out += ['## Drive / ODT settings (typ corner, DQ4 / CA1 / CS2 / CK)', '',
            '| rate | width in/out | case | FPGA drv | FPGA ODT | DRAM ODT | PDDS | CA ODT ' + HDR,
            '|---|---|---|---|---|---|---|---|' + '---|' * 6]
    for r_ in sorted({r['rate'] for r in R}):
        for wi, wo in ((0.18, 0.25), (0.10, 0.10)):
            rs = sel(R, rate=r_, w_in=wi, w_out=wo, pkg='netlen', corner='typ', diff_in='0.14/0.15')
            cases = list(dict.fromkeys(r['case'] for r in rs if r['case'].startswith(('w_dq4', 'r_dq4', 'ca1', 'cs2', 'ck'))))
            for c in cases:
                w = worst(sel(rs, case=c)); r0 = sel(rs, case=c)[0]
                out.append(f"| {r_:g} | {wi:.2f}/{wo:.2f} | {c} | {r0['fdrv']} | {r0['fodt']} | {r0['modt']} | {r0['pdds']} | "
                           f"{r0['caodt']} | " + fmt(w) + ' |')
    out.append('')
    # package model
    out += ['## FPGA package model: net-length line vs the vendor file\'s lumped pin RLC (typ)', '',
            '| rate | width in/out | group | package ' + HDR, '|---|---|---|---|' + '---|' * 6]
    for r_ in sorted({r['rate'] for r in R}):
        for wi, wo in ((0.18, 0.25), (0.10, 0.10), (0.09, 0.09)):
            for kind, title, f in GROUPS[:2] + GROUPS[5:6]:
                for pkg in ('netlen', 'file'):
                    rs = sel(R, rate=r_, w_in=wi, w_out=wo, pkg=pkg, corner='typ', case=f, diff_in='0.14/0.15')
                    if rs: out.append(f'| {r_:g} | {wi:.2f}/{wo:.2f} | {title.split(" (")[0]} | {pkg} | ' + fmt(worst(rs)) + ' |')
    out.append('')
    # pairs
    out += ['## Pair geometry (DQS, CK), SE at today\'s width', '',
            '| rate | corner | inner w/gap | outer w/gap | group ' + HDR, '|---|---|---|---|---|' + '---|' * 6]
    for r_ in sorted({r['rate'] for r in R}):
        for corner in ('typ', 'min'):
            for di, do in sorted({(r['diff_in'], r['diff_out']) for r in R}, key=lambda x: x[0], reverse=True):
                for kind, title, f in GROUPS[2:5]:
                    rs = sel(R, rate=r_, corner=corner, diff_in=di, diff_out=do, w_in=0.18, w_out=0.25, pkg='netlen', case=f)
                    if rs: out.append(f'| {r_:g} | {corner} | {di} | {do} | {title} | ' + fmt(worst(rs)) + ' |')
    out.append('')
if X:
    out += ['## Crosstalk (three coupled lines, 25 mm, ngspice CPL; DQ write, FPGA 40 Ω → DRAM ODT 60, typ)', '',
            '| rate | layer | w / gap (mm) | victim eye: quiet aggressors EH / margin t | random aggressors EH / margin t | '
            'victim quiet, aggressors in phase: peak noise far end / near end (mV) |', '|---|---|---|---|---|---|']
    for r_ in sorted({r['rate'] for r in X}):
        for g in dict.fromkeys((r['xt_layer'], r['xt_w'], r['xt_gap']) for r in X):
            base = f"xt_r{r_:g}_{g[0]}_w{g[1]:.2f}_g{g[2]:.2f}"
            q = sel(X, point=base + '_quiet', case='xv'); rnd = sel(X, point=base + '_rand', case='xv')
            nz = sel(X, point=base + '_noise', case='xv')
            if not (q and rnd and nz): continue
            wq, wr = worst(q), worst(rnd)
            far = max(abs(r['vmax_mV']) for r in nz if r['where'] in ('ball', 'die'))
            ne = max(r['ne_peak_mV'] for r in nz)
            out.append(f"| {r_:g} | {g[0]} | {g[1]:.2f} / {g[2]:.2f} | {wq['eh']:.0f} / {wq['tm']:+.0f} | "
                       f"{wr['eh']:.0f} / {wr['tm']:+.0f} | {far:.0f} / {ne:.0f} |")
    out.append('')
if Z:
    out += ['## Field solve (zsolve_widths.py)', '', '| layer | kind | w (mm) | gap (mm) | Z (Ω) | ps/mm |', '|---|---|---|---|---|---|']
    for z in Z:
        g = z['gap'] if z['gap'] != '' else ''
        out.append(f"| {z['layer']} | {z['kind']} | {z['w']:.2f} | {g} | {z['Z']:.1f} | {z['ps_mm']:.3f} |")
open(os.path.join(RES, os.path.splitext(sys.argv[1] if len(sys.argv) > 1 else 'results.csv')[0] + '.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
