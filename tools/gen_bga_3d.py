#!/usr/bin/env python3
"""3D models (VRML) for the board's BGAs, which KiCad's library has no model for: python3 tools/gen_bga_3d.py

Writes lib/3dmodels/<footprint>.wrl: a dark body box with a pin-1 dot, on a ball under every pad of the footprint
(lib/ti135_card.pretty). The footprints reference them as ${KIPRJMOD}/../lib/3dmodels/<footprint>.wrl, so the
3D viewer and the CI render (kicad-board-plots, render-3d) find them. For looks only (no STEP, no MCAD use).

Dimensions (mm): body D x E, height A (top of the body above the board), standoff A1, ball diameter b.
  U501 Ti135N484 (LFBGA-484): Efinix 3D model 3Dmodel-3-N484-v1.1.step (reference/efinix, not in git): 18 x 18,
       ball radius 0.25 with 0.25 below the substrate, substrate top 1.789 above its bottom -> A 2.04, A1 0.25, b 0.50.
  U801 LPDDR4 (BGA-200): SK hynix 200-ball FBGA spec of the H9HCNNN* family (H9HCNNNBKUMLXR / H9HCNNNCPUMLHR
       datasheets, 2.2 Mechanical specification): 10 x 15, total 0.90 +-0.10, standoff 0.22, ball 0.30 (0.32 reflowed).
  U1001 eMMC (153-ball): Kioxia P-WFBGA153-1113-0.50 (THGAMRG9T23BAIL datasheet, same package as THGAMVG7T13BAIL):
       11.5 x 13, H 0.8 max, standoff 0.22, ball 0.30.
  U601 IS25WP128-RHLE (24-ball TFBGA 6x8 5x5, package H): ISSI IS25WP128 rev. B4 10.6: A 1.20 max, A1 0.31 nom,
       b 0.40 nom, 6 x 8.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRETTY = os.path.join(ROOT, "lib", "ti135_card.pretty")
OUT = os.path.join(ROOT, "lib", "3dmodels")

#           footprint                                    D (x)  E (y)  A     A1    b
MODELS = [("LFBGA-484_18x18mm_Layout22x22_P0.8mm",       18.0, 18.0, 2.04, 0.25, 0.50),
          ("BGA-200_10x15mm_Layout12x22_P0.8x0.65mm",    10.0, 15.0, 0.90, 0.22, 0.30),
          ("LFBGA-153_11.5x13mm_Layout14x14_P0.5mm",     11.5, 13.0, 0.80, 0.22, 0.30),
          ("MX25U25645G_CSP24_6x8mm_P1.0mm",              6.0,  8.0, 1.20, 0.31, 0.40)]

U = 1 / 2.54          # KiCad VRML unit is 0.1 inch
BODY = "0.13 0.13 0.14"
BALL = "0.78 0.78 0.80"
DOT = "0.55 0.55 0.57"


def mat(rgb, spec="0.2 0.2 0.2", shin="0.3"):
    return f"Appearance {{ material Material {{ diffuseColor {rgb} specularColor {spec} shininess {shin} }} }}"


def model(name, D, E, A, A1, b):
    src = open(os.path.join(PRETTY, name + ".kicad_mod")).read()
    balls = [(float(x), float(y)) for x, y in re.findall(r'\(pad "[^"]+" smd \w+\s*\(at ([-0-9.]+) ([-0-9.]+)', src)]
    r = b / 2
    out = ["#VRML V2.0 utf8", f"# {name}: generated by tools/gen_bga_3d.py (body {D} x {E} x {A} mm, "
           f"standoff {A1}, ball {b}, {len(balls)} balls)",
           # body: from the standoff to A; KiCad: x right, y up (-pcb y), z up
           f"Transform {{ translation 0 0 {(A1 + A) / 2 * U:.5f} children [ Shape {{ appearance {mat(BODY)} "
           f"geometry Box {{ size {D * U:.5f} {E * U:.5f} {(A - A1) * U:.5f} }} }} ] }}"]
    # pin-1 dot near the A1 corner (top left in the footprint, -x / -y)
    dr = min(0.5, 0.06 * min(D, E)); inset = dr + min(0.6, 0.06 * min(D, E))
    out.append(f"Transform {{ translation {(-D / 2 + inset) * U:.5f} {(E / 2 - inset) * U:.5f} {(A + 0.005) * U:.5f} "
               f"rotation 1 0 0 1.5708 children [ Shape {{ appearance {mat(DOT)} "
               f"geometry Cylinder {{ radius {dr * U:.5f} height {0.01 * U:.5f} }} }} ] }}")
    shape = f"DEF BALL Shape {{ appearance {mat(BALL, '0.6 0.6 0.6', '0.6')} geometry Sphere {{ radius {r * U:.5f} }} }}"
    for k, (x, y) in enumerate(balls):   # squashed sphere: bottom on the board, top under the body
        out.append(f"Transform {{ translation {x * U:.5f} {-y * U:.5f} {A1 / 2 * U:.5f} "
                   f"scale 1 1 {A1 / b:.4f} children [ {shape if k == 0 else 'USE BALL'} ] }}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for m in MODELS:
        path = os.path.join(OUT, m[0] + ".wrl")
        open(path, "w").write(model(*m))
        print(os.path.relpath(path, ROOT))
