#!/usr/bin/env python3
"""Build protected_nets.txt and protected_footprints.txt from the board netlist.

    tools/p2k/bin/kipy tools/protected_nets.py [BOARD]

Tiers:
  A  signal nets of the frozen interfaces: every non-rail net on a pad of the LPDDR4 (U801),
     the QSPI flash (U601) or the eMMC (U1001); the net on the far side of a resistor on such
     a net (series terminations, ZQ/RSET-type references); and the non-rail nets on the
     FPGA's DDR-bank balls (pin function containing "DDR").
     Everything on these nets is frozen: tracks, vias, and every footprint with a pad on them.
  B  shared rails that these devices and the DDR bank balls sit on (GND, 1V1, ...). They also
     feed the rest of the board, so only their copper inside the frozen regions is frozen
     (see verify_protected.py); new copper may be added, zones may be extended.
A rail is a net with RAIL_MIN_PADS pads or more.
"""
import sys
import collections
import pcbnew

DEVICES = ("U801", "U601", "U1001")      # LPDDR4, QSPI flash, eMMC
SOC = "U501"
FROZEN_SHEETS = ("08_lpddr4.kicad_sch", "10_emmc.kicad_sch")
RAIL_MIN_PADS = 20
DECAP_RANGE_MM = 3.0                     # rail-to-rail caps this close to a device, on its sheet, are its decoupling

board_path = sys.argv[1] if len(sys.argv) > 1 else "kicad/ti135_card.kicad_pcb"
b = pcbnew.LoadBoard(board_path)
fps = {f.GetReference(): f for f in b.GetFootprints()}

npads = collections.Counter(p.GetNetname() for f in fps.values() for p in f.Pads())
rails = {n for n, k in npads.items() if n and k >= RAIL_MIN_PADS}


def signal(n):
    return n and n not in rails and not n.startswith("unconnected-")


why = {}                                  # tier A net -> reason
for ref in DEVICES:
    for p in fps[ref].Pads():
        if signal(p.GetNetname()):
            why.setdefault(p.GetNetname(), f"{ref} pad")
for ref, f in sorted(fps.items()):        # far side of resistors on those nets
    pads = [p for p in f.Pads() if p.GetNumber()]     # 0201 footprints carry unnumbered paste pads
    if not ref.startswith("R") or len(pads) != 2:
        continue
    a, c = pads[0].GetNetname(), pads[1].GetNetname()
    for near, far in ((a, c), (c, a)):
        if near in why and why[near].endswith("pad") and signal(far) and far not in why:
            why[far] = f"via {ref} from {near}"
ddr_bank_rails = set()
for p in fps[SOC].Pads():
    if "DDR" in p.GetPinFunction().upper():
        n = p.GetNetname()
        if signal(n):
            why.setdefault(n, f"{SOC} DDR-bank ball {p.GetNumber()} ({p.GetPinFunction()})")
        elif n in rails:
            ddr_bank_rails.add(n)

tier_b = {}
for ref in DEVICES:
    for p in fps[ref].Pads():
        if p.GetNetname() in rails:
            tier_b.setdefault(p.GetNetname(), set()).add(ref)
for n in ddr_bank_rails:
    tier_b.setdefault(n, set()).add(f"{SOC} DDR bank")

# footprints
prot = {}
for ref in DEVICES + (SOC,):
    prot[ref] = "frozen device"
for ref, f in fps.items():
    if f.GetSheetfile() in FROZEN_SHEETS:
        prot.setdefault(ref, f"sheet {f.GetSheetfile()}")
    hit = sorted({p.GetNetname() for p in f.Pads()} & set(why))
    if hit:
        prot.setdefault(ref, f"on {hit[0]}")
for ref, f in fps.items():
    if ref in prot or not ref.startswith("C"):
        continue
    nets = {p.GetNetname() for p in f.Pads() if p.GetNumber()}
    if not nets <= rails:
        continue
    for d in DEVICES:
        if f.GetSheetfile() != fps[d].GetSheetfile():
            continue
        bb = fps[d].GetBoundingBox(False)
        bb.Inflate(pcbnew.FromMM(DECAP_RANGE_MM))
        if bb.Contains(f.GetPosition()) and nets <= {p.GetNetname() for p in fps[d].Pads()}:
            prot[ref] = f"decoupling within {DECAP_RANGE_MM:g} mm of {d}"
            break

cnt = collections.defaultdict(lambda: [0, 0])
for t in b.GetTracks():
    cnt[t.GetNetname()][1 if t.Type() == pcbnew.PCB_VIA_T else 0] += 1

with open("protected_nets.txt", "w") as o:
    o.write(f"# Generated by tools/protected_nets.py from {board_path}. Do not edit by hand.\n")
    o.write("# tier<TAB>net<TAB>tracks<TAB>vias<TAB>reason\n")
    for n in sorted(why):
        o.write(f"A\t{n}\t{cnt[n][0]}\t{cnt[n][1]}\t{why[n]}\n")
    for n in sorted(tier_b):
        o.write(f"B\t{n}\t{cnt[n][0]}\t{cnt[n][1]}\trail on {', '.join(sorted(tier_b[n]))}\n")
with open("protected_footprints.txt", "w") as o:
    o.write(f"# Generated by tools/protected_nets.py from {board_path}. Do not edit by hand.\n")
    o.write("# ref<TAB>value<TAB>layer<TAB>reason\n")
    for ref in sorted(prot, key=lambda r: (r.rstrip("0123456789"), int("0" + r[len(r.rstrip("0123456789")):]))):
        f = fps[ref]
        o.write(f"{ref}\t{f.GetValue()}\t{f.GetLayerName()}\t{prot[ref]}\n")
print(f"tier A nets {len(why)}, tier B rails {len(tier_b)}, protected footprints {len(prot)}")
